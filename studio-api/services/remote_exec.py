"""Run a command on the HTCondor submit host, from the user's pod.

Why this exists
---------------
Pegasus assumes the planner and the schedd live on one machine: it defines the
``local`` site as "the workflow submit node where Pegasus **and** the HTCondor
Schedd is installed". Studio breaks that apart — ``pegasus-plan`` runs in a
per-user pod, the schedd runs on a remote access point — and the planner bakes
*its own* absolute paths into the submit files it writes. Auxiliary jobs in the
local universe then execute on the AP against paths that only exist in the pod.

On 2026-09-02 that made every workflow fail on its first node: the pod resolved
``pegasus-lite-local.sh`` under ``python3.12`` (Ubuntu noble) and the AP under
``python3.13`` (Debian trixie). See #334, and ``services/submit_host.py`` for
the guardrail that detects it. The pod is Debian trixie now too, but that only
removes one way for the paths to diverge — planning on the AP is what makes the
paths right by definition, whatever either side is running.

Planning on the AP fixes it at the source. Verified 2026-09-02 by driving this
module against the live cluster: planning the earthquake workflow produced 14
submit files referencing the AP's ``python3.13`` tree and **zero** referencing
the pod's ``python3.12``.

How
---
An HTCondor **local-universe** job. That gets us remote execution with no new
service, no new credential and no new trust boundary: the pod already holds an
IDTOKEN for this schedd, and local-universe jobs run on the schedd host
immediately rather than waiting for a match. It is also how Pegasus runs its
own auxiliary jobs, so the execution context is the one Pegasus expects.

Two things are load-bearing:

- **The working directory must be on shared storage.** ``ap:/home/<user>`` is
  NFS-mounted into the pod, so anything under ``$HOME`` is visible to both. A
  probe run from ``/tmp`` produced no output file at all — the AP simply could
  not see it.
- **``getenv = false``.** Copying the pod's environment would re-import the
  very thing we are escaping: the pod exports ``PEGASUS_PYTHON=/usr/bin/python3``
  and could export ``PYTHONPATH``, either of which would push the AP's planner
  back at the pod's Pegasus. The environment is set explicitly instead.
"""

from __future__ import annotations

import asyncio
import os
import re
import shlex
import shutil
import time
from pathlib import Path

import structlog

from services import schedd

log = structlog.get_logger()

# Planning a large workflow is not fast; this is a backstop against a job that
# never starts, not a normal-case budget.
_TIMEOUT = float(os.environ.get("STUDIO_REMOTE_EXEC_TIMEOUT", "1800"))

_SUBMIT_RE = re.compile(r"submitted to cluster\s+(\d+)", re.IGNORECASE)


class RemoteExecUnavailable(RuntimeError):
    """The mechanism itself is not usable — not that the command failed."""


def _wrapper_text(
    argv: list[str], cwd: str, rc_path: str, home: str | None = None
) -> str:
    """A wrapper, rather than pointing `executable` straight at the command.

    It gives us the working directory (local-universe `initialdir` would do
    that, but not portably across the shared-filesystem cases), and an exit
    code written to a file. Reading the code from the job log means parsing
    HTCondor's event format; a file is unambiguous.

    It also sets HOME itself (#508). HTCondor replaces HOME in a
    local-universe job with the owner's passwd home, whatever the submit
    file's `environment` says, so the planner saw the user's real home and
    copied it into the workflow's DAGMan environment: DAGMan and
    pegasus-monitord then kept Pegasus's master database and logs in the real
    home, not Studio's. An export in the script runs after HTCondor has built
    the environment, so nothing overrides it.
    """
    quoted = " ".join(shlex.quote(a) for a in argv)
    set_home = f"export HOME={shlex.quote(home)}\n" if home else ""
    return (
        "#!/bin/bash\n"
        "# Generated by studio-api (services/remote_exec.py). Safe to delete.\n"
        f"{set_home}"
        f"cd {shlex.quote(cwd)} || {{ echo 127 > {shlex.quote(rc_path)}; exit 127; }}\n"
        f"{quoted}\n"
        "rc=$?\n"
        f"echo $rc > {shlex.quote(rc_path)}\n"
        "exit $rc\n"
    )


def _submit_text(
    *, wrapper: str, out: str, err: str, logf: str, home: str, user: str, initialdir: str
) -> str:
    # PATH is set explicitly rather than inherited: see the module docstring on
    # why getenv=false matters here.
    #
    # JAVA_TOOL_OPTIONS beside HOME (#489): pegasus-plan is Java, and the JVM
    # takes user.home from passwd, not $HOME. On the submit host passwd names
    # the user's real home, so the planner read *that* ~/.pegasusrc and
    # ignored Studio's: under Open OnDemand, where Studio's home is a directory
    # of its own, the site catalog never loaded.
    env = (
        f"PATH=/usr/bin:/bin:/usr/sbin:/sbin HOME={home} USER={user} LANG=C.UTF-8 "
        f"JAVA_TOOL_OPTIONS=-Duser.home={home}"
    )
    return (
        "universe = local\n"
        f"executable = {wrapper}\n"
        # Without this, HTCondor inherits the *submitting process's* working
        # directory. studio-api runs from /opt/studio-api, which exists only
        # inside the pod, so every job was held with "Cannot access initial
        # working directory". Hand-testing from a $HOME path hid it exactly
        # (#341).
        f"initialdir = {initialdir}\n"
        f"output = {out}\n"
        f"error = {err}\n"
        f"log = {logf}\n"
        "getenv = false\n"
        f'environment = "{env}"\n'
        # The working directory is on shared storage, so HTCondor must not
        # try to stage anything: a copy would defeat the point and could
        # shadow the real files.
        "should_transfer_files = NO\n"
        "queue\n"
    )


async def _run(cmd: list[str], timeout: float) -> tuple[int, str, str]:
    proc = await asyncio.create_subprocess_exec(
        *cmd,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=timeout)
    return (
        proc.returncode if proc.returncode is not None else -1,
        stdout.decode("utf-8", errors="replace"),
        stderr.decode("utf-8", errors="replace"),
    )


def available() -> bool:
    """Whether the local-universe mechanism could be used at all."""
    return bool(shutil.which("condor_submit") and shutil.which("condor_wait"))



_TIMED_OUT = "__timed_out__"

# HTCondor user-log event codes. 005 = terminated, 009 = aborted,
# 012 = held. Held is the one condor_wait ignores.
_EV_TERMINATED = re.compile(r"^005 \(", re.MULTILINE)
_EV_ABORTED = re.compile(r"^009 \(", re.MULTILINE)
_EV_HELD = re.compile(r"^012 \(", re.MULTILINE)


async def _hold_reason(cluster_id: str | None) -> str:
    """The schedd's own explanation, which is usually the whole answer."""
    if not cluster_id:
        return "job held"
    # _run returns (rc, stdout, stderr) — three values, unlike the two-value
    # helper in submit_host.py.
    _, out, _ = await _run(
        ["condor_q", cluster_id, "-af", "HoldReason"], timeout=30
    )
    reason = (out or "").strip().splitlines()
    return reason[0][:400] if reason and reason[0] != "undefined" else "job held"


async def _await_completion(
    log_f: Path, cluster: "re.Match[str] | None", budget: float
) -> str | None:
    """Wait for the job to finish. Returns None on completion, else why not.

    Polls the user log because it is the one place that records a hold, and
    because it is a local file on shared storage — no repeated queries to the
    schedd for something that may take half an hour.
    """
    cluster_id = cluster.group(1) if cluster else None
    deadline = time.monotonic() + budget
    while time.monotonic() < deadline:
        try:
            text = log_f.read_text(errors="replace")
        except OSError:
            text = ""
        if _EV_TERMINATED.search(text):
            return None
        if _EV_HELD.search(text):
            return await _hold_reason(cluster_id)
        if _EV_ABORTED.search(text):
            return "the job was removed before it ran"
        await asyncio.sleep(2)
    return _TIMED_OUT


async def run_on_submit_host(
    argv: list[str],
    *,
    cwd: str,
    scratch_dir: str,
    timeout: float | None = None,
) -> tuple[int, str]:
    """Run `argv` on the submit host. Returns (exit_code, combined output).

    Mirrors the contract of `run_flow._capture` so a stage can swap local for
    remote execution without changing how it reports.

    `scratch_dir` must be on storage the submit host shares with this pod —
    somewhere under `$HOME`.
    """
    if not available():
        raise RemoteExecUnavailable("condor_submit/condor_wait not found")

    scratch = Path(scratch_dir)
    scratch.mkdir(parents=True, exist_ok=True)
    stamp = f"{int(time.time() * 1000)}"
    wrapper = scratch / f"remote-{stamp}.sh"
    out_f = scratch / f"remote-{stamp}.out"
    err_f = scratch / f"remote-{stamp}.err"
    log_f = scratch / f"remote-{stamp}.log"
    rc_f = scratch / f"remote-{stamp}.rc"
    sub_f = scratch / f"remote-{stamp}.sub"

    home = os.environ.get("HOME", str(Path.home()))
    user = os.environ.get("USER") or os.environ.get("LOGNAME") or "studio"

    wrapper.write_text(_wrapper_text(argv, cwd, str(rc_f), home=home))
    wrapper.chmod(0o755)
    sub_f.write_text(
        _submit_text(
            wrapper=str(wrapper),
            out=str(out_f),
            err=str(err_f),
            logf=str(log_f),
            home=home,
            user=user,
            # The scratch dir is on shared storage by contract, so it is a
            # directory the submit host can definitely chdir into.
            initialdir=str(scratch),
        )
    )

    budget = timeout if timeout is not None else _TIMEOUT
    code, sub_out, sub_err = await _run(["condor_submit", str(sub_f)], timeout=120)
    if code != 0:
        raise RemoteExecUnavailable(
            f"condor_submit failed: {(sub_err or sub_out).strip()[:300]}"
        )
    cluster = _SUBMIT_RE.search(sub_out)

    # Ask the schedd to start it now (#488, #494): local-universe jobs are
    # otherwise started from its periodic timer, so every remote step could
    # sit idle for up to five minutes first. See services/schedd.py.
    schedd.nudge()

    # Watch the job log rather than using `condor_wait`. condor_wait returns
    # on termination but not on *hold*, and a held job never terminates — so a
    # misconfigured submit sat there until the 30-minute timeout with no
    # explanation, which is exactly how the initialdir bug presented (#341).
    # Reading the log lets a hold fail immediately, carrying its own reason.
    held_reason = await _await_completion(log_f, cluster, budget)
    if held_reason is not None:
        if cluster:
            await _run(["condor_rm", cluster.group(1)], timeout=60)
        if held_reason == _TIMED_OUT:
            return 124, (
                f"Timed out after {int(budget)}s waiting for the submit host to "
                f"run {shlex.join(argv)}."
            )
        return 126, (
            f"The submit host refused to run {shlex.join(argv)}: {held_reason}"
        )

    def _read(p: Path) -> str:
        try:
            return p.read_text(errors="replace")
        except OSError:
            return ""

    stdout, stderr = _read(out_f), _read(err_f)
    rc_text = _read(rc_f).strip()
    if rc_text.isdigit():
        rc = int(rc_text)
    else:
        # No rc file means the wrapper never reached its last line — the job
        # was held, evicted or killed. Report a failure rather than guessing
        # success from an empty file.
        rc = 125
        stderr += (
            "\n[studio] The submit host did not report an exit code for this "
            "command; the job may have been held or evicted."
        )

    log.info(
        "remote_exec_finished",
        argv0=argv[0],
        rc=rc,
        cluster=cluster.group(1) if cluster else None,
    )
    combined = (stdout + ("\n" if stdout and stderr else "") + stderr).strip()

    # Six files per invocation, in the user's project directory. Tidy up when
    # the command succeeded and the output is already in hand; keep everything
    # on failure, because the submit file and the job log are exactly what
    # someone debugging a failed plan needs.
    if rc == 0:
        for f in (wrapper, out_f, err_f, log_f, rc_f, sub_f):
            try:
                f.unlink(missing_ok=True)
            except OSError:
                pass  # A leftover file is not worth failing a good run over.

    return rc, combined
