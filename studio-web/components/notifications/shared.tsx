"use client";

import type { NotificationSeverity } from "@/lib/api/client";

/** Tailwind text-color class for a severity's icon/accent. */
export function severityAccent(severity: NotificationSeverity): string {
  switch (severity) {
    case "success":
      return "text-emerald-500";
    case "warning":
      return "text-amber-500";
    case "error":
      return "text-rose-500";
    default:
      return "text-blue-500";
  }
}

/** Left border-color class used by toasts. */
export function severityBorder(severity: NotificationSeverity): string {
  switch (severity) {
    case "success":
      return "border-l-emerald-500";
    case "warning":
      return "border-l-amber-500";
    case "error":
      return "border-l-rose-500";
    default:
      return "border-l-blue-500";
  }
}

